import java.util.*;
public class characterAtoZ {
    public static void main(String args[]){
        int count = 0;
        int ch = 'a';
        char x = 'a';
        while(count<26){
            System.out.print(x+" is ");
            System.out.println(ch);
            ch++;
            count++;
            x++;
        }
    }
    
}
